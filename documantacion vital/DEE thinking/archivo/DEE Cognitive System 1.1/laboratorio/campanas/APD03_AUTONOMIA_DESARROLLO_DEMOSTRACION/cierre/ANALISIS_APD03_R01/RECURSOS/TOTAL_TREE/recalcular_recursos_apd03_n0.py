"""Recalculate archived host/resource measurements. No DEE, no new tasks.

The input is a compact exported directory with MAIN/, TOTAL_TREE/ and IO/.
Timing observations cannot be regenerated by this arithmetic recalculation.
"""
import argparse,gzip,hashlib,json,statistics
from collections import defaultdict
from pathlib import Path

def read(p):
    data=Path(p).read_bytes()
    return json.loads(gzip.decompress(data)if str(p).endswith('.gz')else data)
def lines(p):return [json.loads(line)for line in Path(p).read_bytes().splitlines()if line.strip()]
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def cpu(d):return d['cpu_user_seconds']+d['cpu_kernel_seconds']
def phase(tag):
    if 'admission'in tag:return 'prepared_anatomy'
    if 'teach'in tag:return 'explicit_teaching'
    if 'panel'in tag:return 'material_verification'
    if 'renew'in tag:return 'prepared_access_renewal'
    if 'init'in tag:return 'environment_goal_setup'
    if 'quality'in tag:return 'two_provider_quality_with_feedback'
    if 'composition'in tag:return 'operator_ordered_composition'
    if 'luma'in tag or'nara'in tag:return 'learned_signal_use'
    return 'functional_use_and_return'

def calculate(folder):
    folder=Path(folder);main=folder/'MAIN/EVIDENCIA_MAIN';summary=read(main/'REGISTROS_VENTANA.json.gz')
    assert summary['error']is None and summary['sources_unchanged'] and summary['protected_originals_unchanged']
    total=read(folder/'RECURSOS/TOTAL_TREE/RESULTADO_SUPERVISION.json')
    assert total['error']is None and total['returncode']==0 and total['source_hashes_unchanged']
    samples=lines(folder/'RECURSOS/TOTAL_TREE/MUESTRAS_RECURSOS.jsonl')
    io=lines(folder/'MAIN/RECURSOS_OS_NATIVE/MUESTRAS_CLASS8.jsonl');coverage=read(folder/'MAIN/RECURSOS_OS_NATIVE/ALCANCE_Y_CORRECCION.json')
    assert 'class8'in coverage['queries_only'] and coverage['native_ticks']==0
    events=[read(p)for p in sorted((main/'EVENTOS').glob('*.json.gz'))]
    material=[];groups=defaultdict(list)
    for event in events:
        if event['kind']!='material':continue
        result=event['decoded_result'];before=event.get('job_before');after=event.get('job_after')
        row={'id':event['id'],'tag':event['tag'],'phase':phase(event['tag']),
             'observed_latency_ns':event['elapsed_ns'],'driver_client_cpu_ns':event['driver_cpu_ns'],
             'native_before_tick':result['before_tick'],'native_after_tick':result['after_tick'],
             'native_ticks_within_material_request':result['after_tick']-result['before_tick'],
             'native_job_cpu_delta_seconds':None if before is None or after is None else cpu(after)-cpu(before),
             'scope':'Owner job CPU includes its workers during request; latency includes transport/measurement. Not CPU of a single arithmetic operation.'}
        assert row['observed_latency_ns']>=0 and row['native_ticks_within_material_request']>=0
        if row['native_job_cpu_delta_seconds']is not None:assert row['native_job_cpu_delta_seconds']>=0
        groups[row['phase']].append(row);material.append(row)
    final_jobs={}
    for row in io:
        assert all(type(v)is int and v>=0 for v in row['io'].values())
        final_jobs[row['job_name']]=row
    io_lifetime={key:sum(row['io'][key]for row in final_jobs.values())for key in next(iter(final_jobs.values()))['io']}
    own_jobs=[summary['job_first_owner_final'],summary['job_second_owner_final']]
    assert all(job is not None and job['job_active_processes']==0 for job in own_jobs)
    # class9.IoInfo remains in the original records, but is reserved and is NOT
    # taken as a measurement. Never sum nested Job peaks or CPU twice.
    functional={key:{'material_requests':len(rows),
        'latency_ns':{'samples':len(rows),'min':min(x['observed_latency_ns']for x in rows),
            'median':statistics.median(x['observed_latency_ns']for x in rows),'max':max(x['observed_latency_ns']for x in rows),
            'sum':sum(x['observed_latency_ns']for x in rows)},
        'native_job_cpu_delta_seconds':sum(x['native_job_cpu_delta_seconds']for x in rows if x['native_job_cpu_delta_seconds']is not None),
        'material_ticks':sum(x['native_ticks_within_material_request']for x in rows)}for key,rows in groups.items()}
    final=summary['final_stopped_cut']['record'];initial=summary['initial_record']
    pair=summary['final_stopped_cut']
    result={'schema':'APD03.archived_resource_recalculation.R01','new_native_ticks':0,'new_provider_calls':0,
        'measurement_not_reexecuted':True,'energy':'NO MEDIDA','life':summary['life'],
        'evolving_window_seconds':summary['enabled_seconds'],'driver_wall_seconds':summary['driver_wall_seconds'],
        'initial_tick':initial['physical']['tick'],'final_tick':final['physical']['tick'],
        'total_native_tick_delta':final['physical']['tick']-initial['physical']['tick'],
        'total_process_tree':{'wall_seconds':total['wall_seconds'],'cpu_seconds':cpu(total['final_job']),
            'peak_job_committed_bytes':total['final_job']['peak_job_committed_bytes'],
            'memory_limit_bytes':1073741824,'processes_created_in_tree':total['final_job']['job_total_processes'],
            'active_processes_final':total['final_job']['job_active_processes'],'samples':len(samples),
            'scope':'Whole owned driver/client/UI/Native/worker tree. Not the entire computer. Nested values below are NOT added.'},
        'native_jobs_only':{'cpu_seconds_lifetime':sum(cpu(job)for job in own_jobs),
            'peak_job_committed_bytes_max_not_sum':max(job['peak_job_committed_bytes']for job in own_jobs),
            'owner_jobs':len(own_jobs),'workers_and_owner_in_each_job':[job['job_total_processes']for job in own_jobs]},
        'io_native_jobs_only':{'class8_lifetime_totals':io_lifetime,'unique_jobs_observed':len(final_jobs),
            'final_samples':list(final_jobs.values()),'sampling_records':len(io),
            'all_final_jobs_inactive':all(row['job_active_processes']==0 for row in final_jobs.values()),
            'scope':'Logical Windows transfer counters including cache/IPC. Not physical disk bytes or joules; excludes UI/manager clients outside Native Jobs.',
            'late_attachment':coverage['late_attachment'],
            'class9_reserved_IoInfo_excluded':True},
        'request_groups':functional,'material_request_measurements':material,
        'paired_operational_members':pair['verification'],
        'final_native_snapshot_bytes':next(row['bytes']for row in read(main/'PAR_POSTSTOP_FINAL/EXPORTACION_SERVICIO.json')['members']if row['file']=='VIDA.deetsnap.gz')if (main/'PAR_POSTSTOP_FINAL/EXPORTACION_SERVICIO.json').is_file()else None,
        'serialized_native_basic_buffers_bytes':final['physical'].get('basic_buffers_bytes'),
        'limits':['Request phase categories are host-cost bookkeeping, not internal cognitive modules.',
            'Latency samples here cover the35 driver-timed material calls, not the additional queued-ID completion and panel in the second UI. Total-tree CPU/RAM retains both processes. The paused queue interval is not called Native computation latency.',
            'Native I/O observation began after the first owner started; cumulative class8 lifetime totals include earlier work, but earlier phase boundaries have no samples.',
            'Per-request latency/CPU omits some periodic idle work and process startup; the whole-tree total retains them.',
            'CPU/RAM scopes are nested and must not be added; latency samples are interactions of the same life, not independent learners.',
            'Energy, monetary cost and independent-computer performance are not measured.'],
        'source_members':[{'path':str(p.relative_to(folder)),'bytes':p.stat().st_size,'sha256':sha(p)}for p in [main/'REGISTROS_VENTANA.json.gz',folder/'RECURSOS/TOTAL_TREE/RESULTADO_SUPERVISION.json',folder/'RECURSOS/TOTAL_TREE/MUESTRAS_RECURSOS.jsonl',folder/'MAIN/RECURSOS_OS_NATIVE/MUESTRAS_CLASS8.jsonl',folder/'MAIN/RECURSOS_OS_NATIVE/ALCANCE_Y_CORRECCION.json']]}
    return result

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--evidence',type=Path,required=True);ap.add_argument('--out',type=Path);a=ap.parse_args()
    value=calculate(a.evidence);data=(json.dumps(value,ensure_ascii=False,sort_keys=True,indent=2)+'\n').encode('utf8')
    if a.out:
        with a.out.open('xb')as stream:stream.write(data)
    else:print(data.decode('utf8'))
if __name__=='__main__':main()
