"""Refresh only generated analysis inventory after the final stage editorial.

Keep previous generated bytes in a new external proof directory. Copy the
existing original budget without changing its clock. No closed component,
original report, S, Native state or distribution ZIP is edited.
"""
import argparse,hashlib,json,os,shutil
from pathlib import Path

CLOSED=('MAIN','MECANISMO','CURVAS','R04','REFERENCIAS','WSLS_ESTANDAR','ENTRADA_UI','SERVICIO_MAIN','VALIDACION_FULL')


def read(path):return json.loads(Path(path).read_bytes())


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def rows(root):return [{'file':p.relative_to(root).as_posix(),'bytes':p.stat().st_size,'sha256':sha(p)}for p in sorted(root.rglob('*'))if p.is_file()]


def replace_generated(path,value):
    temp=path.with_name(path.name+'.nuevo_N0')
    with temp.open('x',encoding='utf8',newline='\n')as stream:
        json.dump(value,stream,ensure_ascii=False,sort_keys=True,indent=2);stream.write('\n')
    os.replace(temp,path)


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--stage',required=True,type=Path);ap.add_argument('--out',required=True,type=Path)
    ap.add_argument('--budget-file',required=True,type=Path)
    ap.add_argument('--editorial-code',required=True,type=Path);ap.add_argument('--editorial-proof',required=True,type=Path)
    args=ap.parse_args();stage=args.stage.resolve(strict=True);out=args.out.resolve()
    if stage.name!='ANALISIS_APD03_R02'or(stage/'MANIFIESTO_FINAL_ANALISIS.json').exists():raise ValueError('Require the unsealed R02 stage')
    if out.exists()or out.is_relative_to(stage):raise ValueError('Preserve previous proof/output')
    out.mkdir(parents=True)
    closed_before={name:rows(stage/name)for name in CLOSED}
    for name in CLOSED:
        value=read(stage/name/'MANIFIESTO.json')
        for row in value.get('files',value.get('members',[])):
            relative=row.get('file',row.get('path'));path=(stage/name/relative).resolve(strict=True)
            if not path.is_relative_to((stage/name).resolve())or path.stat().st_size!=row['bytes']or sha(path)!=row['sha256']:raise ValueError('Closed component differs before refresh')
    backups={}
    for relative in('RECALCULO/ENTRADAS_ESPERADAS.json','CANDIDATO_NO_SELLADO.json','INDICE_FUENTES_Y_OMISIONES.json'):
        source=stage/relative;dest=out/Path(relative).name;shutil.copyfile(source,dest);backups[relative]=sha(source)
    copied=[]
    for source,relative,kind in[(args.budget_file,'RECURSOS/PRESUPUESTO_E_IDENTIDAD_INICIAL.json','original_monotonic_budget_exact_no_reset'),
        (args.editorial_code,'CODIGO_DE_CIERRE/finalizacion/'+args.editorial_code.name,'post_Full_editorial_instrument_not_Native'),
        (args.editorial_proof,'EDITORIAL_FINAL/'+args.editorial_proof.name,'actual_post_Full_stage_editorial_receipt'),
        (Path(__file__),'CODIGO_DE_CIERRE/finalizacion/'+Path(__file__).name,'generated_inventory_refresh_instrument')]:
        source=source.resolve(strict=True);data=source.read_bytes();digest=hashlib.sha256(data).hexdigest();dest=stage/relative
        dest.parent.mkdir(parents=True,exist_ok=True)
        if dest.exists():
            if dest.read_bytes()!=data:raise ValueError('Existing added member differs: '+relative)
        else:
            with dest.open('xb')as stream:stream.write(data)
        if source.read_bytes()!=data:raise ValueError('Input changed during copy')
        copied.append({'source':str(source),'file':relative,'bytes':len(data),'sha256':digest,'kind':kind})
    index=read(stage/'INDICE_FUENTES_Y_OMISIONES.json');known={row['file']for row in index['copied']}
    index['copied'].extend(row for row in copied if row['file']not in known)
    index['final_stage_editorial']='Post-Full editorial applied only to superior analysis reports; closed components unchanged. Prior generated inventory retained externally.'
    replace_generated(stage/'INDICE_FUENTES_Y_OMISIONES.json',index)
    all_rows=[r for r in rows(stage)if r['file']not in('RECALCULO/ENTRADAS_ESPERADAS.json','CANDIDATO_NO_SELLADO.json')]
    groups={}
    for row in all_rows:groups.setdefault(row['sha256'],[]).append(row)
    candidate=read(stage/'CANDIDATO_NO_SELLADO.json')
    candidate.update({'status':'POST_EDITORIAL_READY_FOR_ROOT_SEAL_NO_ZIP','files_before_inventory_and_candidate':len(all_rows),
        'expanded_bytes_before_inventory_and_candidate':sum(r['bytes']for r in all_rows),
        'global_jobs':len(read(stage/'RECALCULO/PLAN_GLOBAL.json')['jobs']),
        'exact_duplicate_bytes_retained_for_relative_paths':sum(sum(r['bytes']for r in group[1:])for group in groups.values()),
        'post_Full_editorial_receipt':copied[2]['file'],'original_budget_member':copied[0]['file'],
        'inventory_refreshed_after_editorial':True,'final_ZIP_created':False})
    replace_generated(stage/'CANDIDATO_NO_SELLADO.json',candidate)
    expected=[r for r in rows(stage)if r['file']!='RECALCULO/ENTRADAS_ESPERADAS.json']
    replace_generated(stage/'RECALCULO/ENTRADAS_ESPERADAS.json',{'files':expected,'excludes_own_hash':True,
        'candidate_not_final_manifest':True,'refreshed_after_final_editorial':True})
    closed_after={name:rows(stage/name)for name in CLOSED}
    if closed_before!=closed_after:raise ValueError('Closed component changed during generated refresh')
    proof={'schema':'APD03.final_stage.generated_inventory_refresh.N0.R02','stage':str(stage),'previous_generated_sha256':backups,
        'copied':copied,'final_inventory_sha256':sha(stage/'RECALCULO/ENTRADAS_ESPERADAS.json'),
        'input_members':len(expected),'final_stage_files':len(rows(stage)),'closed_components_byte_identical':list(CLOSED),
        'new_native_ticks':0,'ZIP_created':False,'budget_clock_reset':False}
    with(out/'RESULTADO_REFRESCO.json').open('x',encoding='utf8')as stream:
        json.dump(proof,stream,ensure_ascii=False,sort_keys=True,indent=2);stream.write('\n')
    print(json.dumps({'inputs':len(expected),'closed_components_unchanged':True,'new_native_ticks':0,'ZIP_created':False,'proof':str(out)}))


if __name__=='__main__':main()
