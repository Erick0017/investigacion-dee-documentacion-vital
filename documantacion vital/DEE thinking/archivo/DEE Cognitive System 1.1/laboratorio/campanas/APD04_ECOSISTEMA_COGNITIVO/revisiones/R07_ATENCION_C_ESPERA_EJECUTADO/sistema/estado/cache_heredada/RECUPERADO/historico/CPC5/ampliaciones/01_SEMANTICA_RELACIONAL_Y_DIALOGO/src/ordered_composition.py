N=67
KEY='cpc5.extension.ordered-composition.v1'


def move(q,d,t=1):return tuple((int(q[i])+int(d[i])*int(t))%N for i in range(3))


def geometry(case):
    order=case.get('order','AB')
    if order not in ('AB','BA'):raise ValueError('Prepared orders AB or BA required')
    tr=case.get('translation',[0,0,0])
    if len(tr)!=3 or any(type(x)is not int for x in tr):raise ValueError('Three integer translations')
    translated=lambda q:move(q,tr)
    first=(25,25,8)
    second=(30,30,8) if order=='AB' else (25,30,8)
    directions={'A':(1,0,0),'B':(-1,0,0)}
    stages=[]
    for index,name in enumerate(order):
        meeting=translated(first if index==0 else second);tick=11+5*index
        stages.append({'name':name,'direction':directions[name],'meeting':meeting,'meeting_tick':tick,
                       'hub':move(meeting,directions[name],-(tick-3))})
    backups=[{'name':'A','direction':(1,0,0),'hub':translated((20,20,30))},
             {'name':'B','direction':(-1,0,0),'hub':translated((40,20,45))}]
    banks={'V':translated((30,33,8)),'D':translated((28,33,8))}
    return {'N':N,'order':order,'translation':tr,'stages':stages,'backups':backups,
            'query_site':translated((20,20,8)),'query_direction':[1,1,0],'query_tick':6,
            'banks':banks,'environment_contact_tick':19,'backup_probe_tick':67,
            'backup_meeting_tick':70,'components':4,'initial_material_sites':0,
            'roles':'A and B are investigator component identifiers, not acquired pronouns or temporal concepts',
            'designed':'Order/routing, teaching opportunities, two equal environment inputs and backup interfaces',
            'acquired':'Directional mobile states generated by admitted cue/report collisions; no prepared trained RAW',
            'scope':'Ordered physical composition. No claim of abstract ANTES, participant identity inference, or free grammar.'}


def ports_for(spec):
    ports=[]
    for component in spec['stages']+spec['backups']:
        name=component['name']+('.backup' if component in spec['backups'] else '.main')
        hub=component['hub']
        for label,dr in (('cue',(0,-1,0)),('plus',(1,1,0)),('minus',(-1,1,0))):
            ports.append(interface(name+'.'+label,move(hub,dr,-3),dr))
        if component in spec['backups']:
            ports.append(interface(name+'.probe',move(hub,(0,-1,0),-3),(0,-1,0)))
    ports.append(interface('common.query',spec['query_site'],(1,1,0)))
    for name,site in spec['banks'].items():
        ports.append(interface('environment.'+name,move(site,(0,-1,0),-3),(0,-1,0)))
    return ports


class OrderedSession:
    def __init__(self,world,spec,state):self.world,self.spec,self.state=world,spec,state

    @classmethod
    def create(cls,case=None):
        import dee_thinking as d
        spec=geometry(case or {})
        recipe=d.OrganizationRecipe.research(N,[],0);recipe.interfaces=ports_for(spec)
        recipe.execution=d.TickOptions(d.Backend.LAZY,1)
        world=d.OrganizationalWorld.create(recipe)
        session=cls(world,spec,{'version':1,'tick':0,'geometry':spec,'calls':[],
                              'scope':'Prepared physical ports and receipts; no expected answer or learned correspondence cache'})
        session.commit();return session

    def commit(self):
        self.state['tick']=int(self.world.runtime.current_tick)
        self.world.runtime.set_snapshot_metadata(KEY,json.dumps(self.state,separators=(',',':')))

    def submit(self,port,load,tick,probe=False,origin='EXTERNAL_CURRENT_EVENT'):
        if type(load)is not int or not 0<=load<=65535:raise ValueError('uint16 payload required')
        if type(tick)is not int or tick<self.world.runtime.current_tick:raise ValueError('Monotone absolute tick required')
        if port not in {p.name for p in self.world.interfaces}:raise ValueError('Undeclared port')
        r=(self.world.probe if probe else self.world.submit)(port,load,tick)
        self.state['calls'].append({'id':int(r.id),'port':port,'payload':load,'requested_tick':tick,
             'call_tick':int(self.world.runtime.current_tick),'operation':'probe' if probe else 'submit','origin':origin})
        self.commit();return int(r.id)

    def experience(self,name,loads,direction,tick=0,mode='paired',backup=True):
        if name not in ('A','B')or direction not in (-1,1):raise ValueError('Component A/B and direction +/-1 required')
        if mode not in ('paired','unpaired','omitted'):raise ValueError('Unknown experience mode')
        if mode=='omitted':return []
        ids=[]
        for suffix in (('main','backup') if backup else ('main',)):
            ids.append(self.submit(name+'.'+suffix+'.cue',loads[0],tick+int(mode=='unpaired'),origin='OPAQUE_CUE_EXPERIENCE'))
            ids.append(self.submit(name+'.'+suffix+('.plus' if direction>0 else '.minus'),loads[1],tick,
                                   origin='CURRENT_DIRECTIONAL_EVENT'))
        return ids

    def run_until(self,tick):until(self.world,tick);self.commit()

    def save(self,path):
        path=Path(path)
        if path.exists():raise FileExistsError(path)
        path.parent.mkdir(parents=True,exist_ok=True);self.commit();self.world.save_snapshot(str(path))
        return {'file':path.name,'sha256':sha(path),'physical':digest(self.world)}

    @classmethod
    def load(cls,path):
        import dee_thinking as d
        world=d.OrganizationalWorld.load_snapshot(str(path));state=json.loads(world.runtime.snapshot_metadata(KEY))
        if state['version']!=1 or state['tick']!=world.runtime.current_tick or world.runtime.dimension!=N:
            raise ValueError('Ordered session snapshot mismatch')
        spec=state['geometry'];expected=ports_for(spec);actual={p.name:p.channel for p in world.interfaces}
        if set(actual)!={p.name for p in expected}:raise ValueError('Changed interface set')
        for p in expected:
            ch=actual[p.name]
            if (ch.injection_site.x,ch.injection_site.y,ch.injection_site.z)!=(p.channel.injection_site.x,p.channel.injection_site.y,p.channel.injection_site.z):
                raise ValueError('Changed port position')
            if (ch.direction.dx,ch.direction.dy,ch.direction.dz)!=(p.channel.direction.dx,p.channel.direction.dy,p.channel.direction.dz):
                raise ValueError('Changed port direction')
        return cls(world,spec,state)


def run_case(case,out):
    import dee_thinking as d
    out=Path(out);out.mkdir(parents=True,exist_ok=False);started=time.monotonic();engine=identity()
    session=OrderedSession.create(case);spec=session.spec;w=session.world;snapshots=[];trace=[];contexts=[];edits=[]
    def save(label):
        item=session.save(out/(label+'.deetsnap'));snapshots.append(item);return item
    loads=case.get('loads',{'A':[5,7],'B':[6,8]});directions=case.get('directions',{'A':1,'B':-1})
    query=case.get('query',13);backup_query=case.get('backup_query',9)
    put(out/'CONFIG.json',{'case':case,'geometry':spec,'engine':engine,'source_sha256':sha(__file__),
        'frozen_criterion':{'primary':'Use both experience-created directional states in sequence; compare exact vector and load, then equal environmental contact.',
           'AB_BA':'Same ingredients, inventory, loads and v0; prepared ordering/routing differs. Do not call equal scalar outputs equivalent functional structure.',
           'learning':'Opposite/omitted/unpaired histories under identical interfaces are controls.',
           'retention':'Independently exposed backups receive one common query after a quiet interval; extra exposures are counted.',
           'not_claimed':'Abstract order inference, ANTES/DESPUES generality or learned interpersonal roles.'}})
    save('INITIAL_T0')
    for name in ('A','B'):
        session.experience(name,loads[name],directions[name],0,case.get('training_modes',{}).get(name,'paired'))
    session.submit('common.query',query,6,True,'USER_INDUCED_COMMON_QUERY')
    for bank in ('V','D'):session.submit('environment.'+bank,7,16,False,'SAME_CURRENT_ENVIRONMENT_INPUT')
    for item in spec['backups']:session.submit(item['name']+'.backup.probe',backup_query,67,True,'RETENTION_QUERY_WITHOUT_RETEACHING')
    schedule=sorted({0,1,2,3,4,6,9,10,11,12,14,15,16,17,18,19,20,21,66,67,69,70,71,73})
    for tick in schedule:
        session.run_until(tick);w=session.world
        if tick==12 and case.get('edit'):
            kind=case['edit'];first=spec['stages'][0]
            # This declared site is the physical nominal first product, not a search for the desired response.
            dr=(1,1,0) if spec['order']=='AB' else (0,1,0)
            site=move(first['meeting'],dr);before=record(w,site);parent=digest(w);op=operational(w)
            edit=d.ResearchStateEdit();edit.coordinate=d.Coordinate(*site);edit.label='Ordered-composition diagnostic '+kind
            if kind=='remove':edit.raw=0
            elif kind=='sham':edit.raw=int(before['raw'])
            elif kind=='reverse':edit.raw=d.pack_record(before['state'],before['s_reg'],-1,1,0,before['semantic'])
            else:raise ValueError('Unknown diagnostic edit')
            save('MAIN_BEFORE_FORK_T12');fork=w.diagnostic_fork([edit],True)
            assert digest(w)==parent and operational(w)==op
            edits.append({'kind':kind,'tick':tick,'site':site,'before':before,'after':record(fork,site),
                          'MAIN_physical_operative_unchanged':True,'clock_unchanged':record(fork,site)['clock']==before['clock'],
                          'parent':parent,'only_RAW_requested':True})
            session.world=fork;w=fork;session.commit();save('DIAGNOSTIC_T12')
        sites={}
        for item in spec['stages']:
            sites[item['name']+'.meeting']=item['meeting']
            if tick>=3:sites[item['name']+'.nominal_free_segment']=move(item['hub'],item['direction'],tick-3)
        for bank,site in spec['banks'].items():sites['bank.'+bank]=site
        for item in spec['backups']:
            sites[item['name']+'.backup_nominal']=move(item['hub'],item['direction'],max(0,tick-3))
            if tick>=70:
                output_dr=(item['direction'][0],-1,0)
                sites[item['name']+'.backup_post_query']=move(item['hub'],output_dr,tick-70)
        row={'tick':tick,'sites':{name:record(w,q) for name,q in sites.items()}}
        if tick in (2,3,10,11,15,16,18,19,69,70):
            for item in spec['stages']:
                center=item['meeting'];contexts.append({'tick':tick,'component':item['name'],'site':center,
                      'neighborhood':local_context(w,center),'gate':gate(w,center)})
        trace.append(row)
        if tick in (3,6,17,20,73):save('T'+str(tick))
        put(out/'INCREMENTAL.json',{'last_tick':tick,'rows':trace,'edits':edits,'snapshots':snapshots})
    final=digest(session.world);op=operational(session.world)
    loaded=OrderedSession.load(out/'T73.deetsnap')
    technical={'save_load_physical_equal':digest(loaded.world)==final,
               'save_load_session_metadata_equal':loaded.state==json.loads(json.dumps(session.state)),
               'save_load_channels_receipts_equal':{k:operational(loaded.world)[k]for k in ('channels','receipts','protocols')}=={k:op[k]for k in ('channels','receipts','protocols')}}
    first=next(r for r in trace if r['tick']==11);second=next(r for r in trace if r['tick']==16)
    consequence=next(r for r in trace if r['tick']==19);retention=next(r for r in trace if r['tick']==70)
    result={'schema':'CPC5.extension.ordered-composition.measurements.v1','case':case,'status':'MEASURED',
        'source_sha256':sha(__file__),'engine':engine,'geometry':spec,'modality':'DIAGNOSTIC_FORK'if edits else'EXPERIENCE_PROTOCOL',
        'preparations':1,'forks':len(edits),'same_RUNTIME':not bool(edits),'calls':session.state['calls'],
        'receipts':[receipt(session.world,c['id'])for c in session.state['calls']],
        'trace':trace,'local_transition_windows':contexts,'interventions':edits,
        'primary_observations':{'first_encounter':first,'second_encounter':second,'environment_contact':consequence,'retention':retention},
        'snapshots':snapshots,'final':final,'operative_final':op,'technical':technical,
        'host_RAW_writes_in_MAIN':0,'host_clock_writes_in_MAIN':0,
        'resources':{'components':4,'training_inputs_requested':sum(c['origin']in('OPAQUE_CUE_EXPERIENCE','CURRENT_DIRECTIONAL_EVENT')for c in session.state['calls']),
             'primary_queries':1,'backup_queries':2,'environment_inputs':2,'basic_buffers_bytes':32*N**3},
        'scope':spec['scope'],'elapsed_seconds':time.monotonic()-started}
    put(out/'MEASUREMENTS.json',result);assert all(technical.values())
    print(json.dumps({'id':case['id'],'first':first,'second':second,'consequence':consequence,
                      'technical':technical,'elapsed_seconds':result['elapsed_seconds']},ensure_ascii=False),flush=True)
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--config',type=Path);p.add_argument('--case',type=Path)
    p.add_argument('--output',type=Path,required=True);args=p.parse_args()
    if bool(args.config)==bool(args.case):raise ValueError('Choose --config or --case')
    if args.case:run_case(json.loads(args.case.read_text(encoding='utf-8')),args.output)
    else:
        config=json.loads(args.config.read_text(encoding='utf-8'));index=[];args.output.mkdir(parents=True,exist_ok=True)
        for case in config['cases']:
            target=args.output/case['id'];path=target/'MEASUREMENTS.json'
            result=json.loads(path.read_text(encoding='utf-8'))if path.is_file()else run_case(case,target)
            assert result['case']==case
            index.append({'id':case['id'],'measurement':str(path),'sha256':sha(path),'final':result['final'],'technical':result['technical']})
            put(args.output/'INDEX.json',{'configuration_sha256':sha(args.config),'cases':index})


if __name__=='__main__':main()
