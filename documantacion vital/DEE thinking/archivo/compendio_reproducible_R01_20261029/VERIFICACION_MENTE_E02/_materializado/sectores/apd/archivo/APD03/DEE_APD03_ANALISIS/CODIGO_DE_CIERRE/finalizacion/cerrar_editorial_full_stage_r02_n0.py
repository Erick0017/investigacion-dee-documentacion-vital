from pathlib import Path
import shutil


FROZEN = {
    'INFORME_CIENTIFICO_APD03.md': 'e66b9d950a252b4a56e8b3b7be6a0c976cf3698856f80ccfe8746f9fa20ab186',
    'COBERTURA_FRENTES_APD03.json': '968d86f6618a7b46c4c8700487f33d65bbab9087eb865f712fb9fcbfd156281f',
}
MAIN_TICK = 604825
MAIN_SNAPSHOT = 'c7cf2e78837ed5f99c950016314bfe5f8fbfa868f72a67af36a94a78261a24ba'
MAIN_PAIR = '9610905c1c3879fd4de3062894c2978c8cb5187e068185cfe889b7b2ee80a085'
FULL_SHA = 'cfd31e2c8d3caab1ebc2c8fc3568f32261b5deeba0069948804aeea9437d71fa'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def read(path):
    return json.loads(Path(path).read_bytes())


def dump(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode('utf8')


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError('Editorial anchor not unique: ' + old[:100])
    return text.replace(old, new, 1)


def report_facts(report, source):
    if report.get('schema') != 'APD03.exact_full.external_verification.R02':
        raise ValueError('Actual R02 external-verification schema required.')
    if report.get('zip_sha256') != FULL_SHA or report.get('zip_bytes') != 355253621:
        raise ValueError('Verification is not for the same closed exact Full ZIP.')
    if report.get('same_computer_not_independent_hardware') is not True or report.get('original_archive_not_modified') is not True:
        raise ValueError('Report does not preserve the declared scope.')
    execution = report.get('execution') or {}
    proof = report.get('native_proof') or {}
    continuity = proof.get('continuity') or {}
    cuts = proof.get('cuts') or []
    final = continuity.get('final_life') or ((cuts[-1].get('record') or {}) if cuts else {})
    final_physical = final.get('physical') or {}
    successful = (not report.get('error') and execution.get('exit_code') == 0 and
                  report.get('zip_still_exact') is True and report.get('native_execution_started') is True and
                  proof.get('issues') == [] and proof.get('sources_unchanged') is True and
                  continuity.get('imports') == 1 and continuity.get('sequential_owners') == 3 and
                  continuity.get('reopens') == 2 and continuity.get('full_physical_fingerprints_equal_before_new_input') is True)
    artifact_rows = proof.get('actual_goal_artifacts') or []
    facts = {
        'status': 'VERIFICADA_EN_EXTRACCION_LOCAL_SEPARADA' if successful else 'CERRADA_CON_FALLO_O_LIMITES',
        'external_report_file': source.name, 'external_report_sha256': sha(source.read_bytes()),
        'ZIP_sha256': report['zip_sha256'], 'ZIP_bytes': report['zip_bytes'], 'ZIP_members': report.get('zip_members'),
        'same_computer_not_other_human': True, 'native_execution_started': report.get('native_execution_started', False),
        'execution_exit_code': execution.get('exit_code'), 'R02_error': report.get('error'),
        'native_proof_issues': proof.get('issues'), 'personal_life': final.get('life_id'),
        'planned_personal_life_not_a_creation_claim': 'APD03_FULL_R01',
        'personal_final_tick': final_physical.get('tick'), 'new_teacher': proof.get('new_teacher'),
        'baseline_words_RAW': proof.get('baseline_words_RAW'), 'later_words_RAW': proof.get('later_words_RAW'),
        'goal_actions': proof.get('goal_actions'), 'goal_progress': proof.get('goal_progress'),
        'actual_goal_artifacts': artifact_rows, 'continuity': continuity, 'native_inputs': proof.get('native_inputs'),
        'first_start_N0_exit_code': (report.get('first_start_N0') or {}).get('exit_code'),
        'Main_cut_not_changed_by_Full_test': {'life':'APD03_MAIN','tick':MAIN_TICK,'snapshot_sha256':MAIN_SNAPSHOT,'pair_manifest_sha256':MAIN_PAIR},
        'not_knowledge_transferred_back_to_Main': True, 'not_another_computer_or_human': True,
    }
    return facts, successful


def paragraph(facts, success):
    prefix = ('La prueba Full R02 terminó conforme a su protocolo cerrado' if success else
              'La prueba Full R02 quedó cerrada con el fallo o límite que identifica su comprobante')
    text = (prefix + ': ZIP exacto de ' + str(facts['ZIP_bytes']) + 'bytes, SHA256 `' + facts['ZIP_sha256'] +
            '`, comprobante `VALIDACION_FULL/' + facts['external_report_file'] + '` SHA256 `' + facts['external_report_sha256'] +
            '`. La extracción fue en otra carpeta de la misma computadora; no se acredita otro equipo ni otro humano. ')
    if success:
        text += ('La vida de prueba separada `' + str(facts['personal_life']) + '` revisó explícitamente luma a−, ' +
                 'utilizó el objetivo nuevo SUM24,5 y conservó su estado durante tres propietarios secuenciales y dos reaperturas; ' +
                 'su tick final fueT' + str(facts['personal_final_tick']) + '. Son experiencias propias de esa trayectoria de distribución, no nuevas experiencias de APD03_MAIN. ')
        archived = facts['archived_recalculation']
        text += ('El recálculo archivado verificó' + str(archived['checks']) + 'condiciones sin discrepancias: ' +
                 str(archived['material_submissions']) + 'peticiones materiales completadas y' +
                 str(archived['native_unique_receipts']) + 'recibos Native aplicados. Se conservaron los otros quince signos del panel, ' +
                 'incluido nara−, y las seis lecturas MA; luma cambió mediante docencia explícita, no retención de su signo previo. ')
    else:
        text += ('No se sustituye el negativo por un éxito supuesto. Se conservan en el comprobante los pasos ejecutados, el último corte y el error, ' +
                 'sin equiparar una interrupción del comprobador o una dependencia ausente a una incapacidad cognitiva no ensayada. ')
    return text + ('El corte científico MAIN permaneceT604825 y el Word1.17 conserva la misma limitación de validación visual. ' +
                   'R01 había terminado antes de preparar/importar el Runtime: el comprobador omitió la inicialización normal y obtuvo `ModuleNotFoundError`; ' +
                   'no hubo evolución Native. R02 añadió la preparación distribuida mediante `INICIAR.bat usar --help` antes de la sonda de importación, ' +
                   'sin cambiar actor, helper, protocolo, motor ni ZIP. El informe R01 negativo se conserva íntegro.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage', type=Path, required=True)
    parser.add_argument('--full-report', type=Path, required=True)
    parser.add_argument('--r01-report', type=Path, required=True)
    parser.add_argument('--full-recalc-rel', default='VALIDACION_FULL/RECALCULO_FULL.json')
    parser.add_argument('--dossier-rel', default=None, help='Optional stage-relative R02 dossier; append bounded report note only.')
    parser.add_argument('--root-confirmado-full-cerrado-y-stage-r02', action='store_true')
    args = parser.parse_args()
    if not args.root_confirmado_full_cerrado_y_stage_r02:
        raise SystemExit('No edits: explicit Root confirmation after actual Full closure is required.')
    closure_root = Path(__file__).resolve().parents[1]
    stage = args.stage.resolve(strict=True)
    if stage != (closure_root / 'ANALISIS_APD03_R02').resolve():
        raise ValueError('Only the exact new ANALISIS_APD03_R02 stage may be edited.')
    if (stage / 'MANIFIESTO.json').exists():
        raise ValueError('Stage already sealed; create another candidate instead of mutating a seal.')
    revision = stage / 'REVISION_EDITORIAL_FULL_R02'
    if revision.exists():
        raise FileExistsError('An editorial revision already exists; no automatic retry/overwrite.')
    r02_path = args.full_report.resolve(strict=True)
    r01_path = args.r01_report.resolve(strict=True)
    report, r01 = read(r02_path), read(r01_path)
    if r01.get('zip_sha256') != FULL_SHA or not r01.get('error') or r01.get('execution') or r01.get('native_proof'):
        raise ValueError('R01 must be the preserved same-ZIP pre-Native harness negative.')
    facts, success = report_facts(report, r02_path)
    full_recalc_path = (stage / args.full_recalc_rel).resolve(strict=True)
    if not full_recalc_path.is_relative_to(stage):
        raise ValueError('Closed Full recalculation must be inside the assembled stage.')
    full_recalc = read(full_recalc_path)
    if full_recalc.get('schema') != 'APD03.Full.archived_recalculation.R02' or full_recalc.get('zip_sha256') != FULL_SHA:
        raise ValueError('Not the closed archived recalculation of the same exact Full proof.')
    if success and (full_recalc.get('issues') != [] or full_recalc.get('final_tick') != facts['personal_final_tick']):
        raise ValueError('Successful external report differs from its archived recalculation.')
    facts['archived_recalculation'] = {key:full_recalc.get(key) for key in ('checks','issues','material_submissions',
        'material_result_statuses','native_unique_receipts','native_receipt_statuses','one_import',
        'sequential_owners','reopens','final_tick','baseline_and_later_MA_RAW')}
    facts['archived_recalculation']['file'] = full_recalc_path.relative_to(stage).as_posix()
    facts['archived_recalculation']['sha256'] = sha(full_recalc_path.read_bytes())
    facts['R01_pre_Native_harness_negative'] = {'file':r01_path.name,'sha256':sha(r01_path.read_bytes()),
        'evolution_Native_occurred':False,'error':r01['error'],
        'scope_note':'The R01 intention flag did not mean the Native helper was started; no execution/native_proof record exists.'}
    appendix = paragraph(facts, success)
    targets = ['INFORME_CIENTIFICO_APD03.md','COBERTURA_FRENTES_APD03.json',
               'COMPLEMENTOS/CAPACIDADES_POR_VIDA.csv','COMPLEMENTOS/ATRIBUCIONES_E_INCORPORACIONES_APD03.md']
    if args.dossier_rel:
        path = (stage / args.dossier_rel).resolve(strict=True)
        if not path.is_relative_to(stage) or path.suffix.lower() != '.md':
            raise ValueError('Optional dossier must be an existing Markdown file inside stage R02.')
        targets.append(path.relative_to(stage).as_posix())
    before = {rel:(stage / rel).read_bytes() for rel in targets}
    for rel, expected in FROZEN.items():
        if sha(before[rel]) != expected:
            raise ValueError('Scientific preimage differs from its frozen source: ' + rel)
    changed = {}
    text = before['INFORME_CIENTIFICO_APD03.md'].decode('utf8')
    old = 'Estado editorial: borrador científico basado en los cierres locales efectivamente ejecutados. La prueba del ZIP Full final exacto sigue **pendiente** en este corte y debe añadirse con su resultado, tamaño y hash reales; no se anticipa su éxito. Esta redacción no ejecutó Native ni modificó el sistema.'
    text = replace_once(text, old, 'Estado editorial: informe científico cerrado con los resultados Native registrados y el comprobante Full R02 ya terminado. La revisión editorial N0 se limita a actualizar el estado de distribución; conserva el corte MAIN y las limitaciones físicas del sello anterior.')
    old = 'La regeneración y prueba desde el ZIP Full final exacto de `cognitive sistem` son una etapa distinta. **Pendientes en este borrador:** hash/tamaño del ZIP sellado, extracción independiente, petición nueva, docencia realmente distinta, retención, guardado y continuación sin rutas originales. La continuidad local de MAIN y los recálculos portátiles ya ejecutados no sustituyen esa prueba. No se acredita segunda computadora ni uso por otro humano.'
    text = replace_once(text, old, appendix)
    old = 'Decisión: **evidencia suficiente para una demostración más acotada de funciones reales** mediante una trayectoria identificada y sus controles. Una ejecución en vivo desde la distribución final requiere completar primero la prueba Full pendiente; los primarios actuales ya permiten un replay verificable, etiquetado como tal.'
    live = ('La prueba Full local separada añade la comprobación operativa de distribución dentro de su dominio; no acredita otra computadora o humano.' if success else
            'La limitación de la prueba Full impide afirmar independencia operativa completa fuera del alcance efectivamente comprobado.')
    text = replace_once(text, old, 'Decisión: **evidencia suficiente para una demostración más acotada de funciones reales** mediante una trayectoria identificada y sus controles. ' + live + ' Los primarios permiten un replay verificable, etiquetado como tal.')
    text = replace_once(text, 'La prueba Full aún pendiente determinará la afirmación de distribución independiente, no los resultados físicos ya registrados.',
                        'El comprobante Full R02 determina la afirmación acotada de distribución; no reescribe los resultados físicos de MAIN ni convierte la vida de prueba en el mismo individuo.')
    changed['INFORME_CIENTIFICO_APD03.md'] = text.encode('utf8')
    coverage = json.loads(before['COBERTURA_FRENTES_APD03.json'])
    coverage['editorial_status'] = 'Cierre científico con comprobante real Full R02, incorporado sólo en stage final R02; fuentes originales congeladas preservadas.'
    coverage['Full_exact_ZIP_test'] = facts
    coverage['demonstrability']['live_distribution_demonstration_depends_on_Full_test'] = not success
    coverage['demonstrability']['Full_local_proof_completed'] = success
    changed['COBERTURA_FRENTES_APD03.json'] = dump(coverage)
    reader = csv.DictReader(io.StringIO(before['COMPLEMENTOS/CAPACIDADES_POR_VIDA.csv'].decode('utf8'), newline=''))
    headers = reader.fieldnames
    rows = list(reader)
    matches = [row for row in rows if row['vida_o_conjunto_identificado'] == 'Distribucion_Full_final_exacta']
    if len(matches) != 1:
        raise ValueError('Full capability row must be uniquely identifiable.')
    row = matches[0]
    row.update(vida_o_conjunto_identificado=(str(facts['personal_life']) + '_prueba_Full_separada') if facts['personal_life'] else 'Distribucion_Full_R02_sin_vida_final_acreditada',
        tick_inicial=str(MAIN_TICK),tick_final=str(facts['personal_final_tick'] or ''),clase='comprobacion_distribucion_nativa' if facts['native_execution_started'] else 'comprobacion_distribucion_pre_Native',
        capacidad='Independencia_operativa_acotada' if success else 'Limite_distribucion_registrado',
        preparado_externamente='Extraccion_inicializacion_normal_y_protocolo_de_prueba_fijos',
        adquirido_o_producido_por_DEE='Revision_luma_menos_y_goal_nuevo_en_vida_de_prueba' if success else 'Solo_lo_registrado_en_comprobante_real_sin_exito_anticipado',
        disponibilidad_operativa='Comprobada_desde_ZIP_exacto_en_otra_carpeta_local' if success else 'Alcance_limitado_por_resultado_real_R02',
        resultado_y_denominador='Tres_propietarios_dos_reaperturas_objetivo_SUM24_5' if success else 'Fallo_o_limite_preservado_ver_comprobante',
        limites='Misma_computadora_no_otro_humano_no_importa_aprendizaje_a_MAIN_Word_sin_visual',
        evidencia='VALIDACION_FULL/' + r02_path.name)
    csv_out = io.StringIO(newline='')
    writer = csv.DictWriter(csv_out, fieldnames=headers, lineterminator='\n')
    writer.writeheader(); writer.writerows(rows)
    changed['COMPLEMENTOS/CAPACIDADES_POR_VIDA.csv'] = csv_out.getvalue().encode('utf8')
    rel = 'COMPLEMENTOS/ATRIBUCIONES_E_INCORPORACIONES_APD03.md'
    text = before[rel].decode('utf8')
    text = replace_once(text, 'La prueba del ZIP Full final exacto sigue pendiente en el sello científico. Su resultado se añadirá como comprobante posterior separado. No se modifica una fuente congelada para anticipar ese resultado, y ningún éxito de distribución reemplazará los límites cognitivos aquí declarados.',
                        appendix + '\n\nEsta revisión sólo cambia la copia editorial del stageR02: el sello científico previo y sus fuentes permanecen intactos. Ningún resultado de distribución reemplaza los límites cognitivos ni añade a MAIN las experiencias de la vida de prueba.')
    changed[rel] = text.encode('utf8')
    if args.dossier_rel:
        rel = Path(args.dossier_rel).as_posix()
        text = before[rel].decode('utf8')
        changed[rel] = (text.rstrip() + '\n\n## Comprobante Full cerrado de esta edición\n\n' + appendix + '\n').encode('utf8')
    # Compute all edits and reject conflicting report copies before writing anything.
    report_dir = stage / 'VALIDACION_FULL'
    for source in (r01_path,r02_path):
        dest = report_dir / source.name
        if dest.exists() and dest.read_bytes() != source.read_bytes():
            raise ValueError('An existing Full report has different bytes; no overwrite.')
    # Exact preimages remain recoverable; no source outside this stage is edited.
    revision.mkdir()
    edits = []
    for rel in targets:
        path = stage / rel
        preserved = revision / 'ANTES' / rel
        preserved.parent.mkdir(parents=True, exist_ok=True)
        preserved.write_bytes(before[rel])
        path.write_bytes(changed[rel])
        edits.append({'file':rel,'before_bytes':len(before[rel]),'before_sha256':sha(before[rel]),
                      'after_bytes':len(changed[rel]),'after_sha256':sha(changed[rel]),
                      'preimage':preserved.relative_to(stage).as_posix()})
    report_dir.mkdir(exist_ok=True)
    for source in (r01_path,r02_path):
        dest = report_dir / source.name
        if not dest.exists():
            shutil.copyfile(source,dest)
    record = {'schema':'APD03.editorial_full_stage_R02.N0.R01','created_utc':datetime.now(timezone.utc).isoformat(),
              'new_native_ticks':0,'stage':str(stage),'sources_originally_frozen':FROZEN,
              'actual_Full_result':facts,'edits':edits,'Main_tick_unchanged':MAIN_TICK,
              'no_engine_kernel_snapshot_or_S_edit':True,'no_manifest_or_ZIP_mutation':True,
              'global_inputs_inventory_must_be_regenerated_before_seal':True,
              'Word_1_17_visual_scope_unchanged':True}
    (revision / 'REGISTRO_EDICION_FULL_R02.json').write_bytes(dump(record))
    print(json.dumps({'updated_files':len(edits),'Full_status':facts['status'],'new_native_ticks':0,
                      'regenerate_global_inputs_before_seal':True},ensure_ascii=False))


if __name__ == '__main__':
    main()
