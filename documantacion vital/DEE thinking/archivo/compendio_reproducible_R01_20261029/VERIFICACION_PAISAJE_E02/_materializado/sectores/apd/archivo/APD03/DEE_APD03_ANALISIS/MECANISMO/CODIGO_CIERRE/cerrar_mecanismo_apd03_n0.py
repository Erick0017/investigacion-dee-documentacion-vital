"""Seal existing R01/R02/R03 evidence, never restore/advance a native world.

The compact stage omits only complete snapshots and earlier regenerable N0
reports. All omitted files retain exact original local path, size and SHA.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


def sha(path):
    digest=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda:stream.read(1048576),b''):digest.update(block)
    return digest.hexdigest()


def emit(path,body):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('x',encoding='utf8') as stream:
        json.dump(body,stream,ensure_ascii=False,sort_keys=True,indent=2);stream.write('\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--lab',required=True,type=Path)
    parser.add_argument('--evidence-root',required=True,type=Path)
    parser.add_argument('--out',required=True,type=Path)
    args=parser.parse_args()
    if args.out.exists():raise FileExistsError('A new sealed stage is required; preserve prior bytes')
    args.out.mkdir(parents=True)
    cases=[('SENSOR_MOVIL_R01','recalcular_cribados_sensores_n0.py'),
        ('SENSOR_BALANCEADO_R02','recalcular_cribados_sensores_n0.py'),
        ('APLICACION_CONTEXTUAL_R03','recalcular_aplicacion_contextual_n0.py')]
    selected=[];omitted=[];source_before={}
    for case,_ in cases:
        source=args.evidence_root/case
        if not (source/'RESULTADOS.json').is_file():raise FileNotFoundError(source/'RESULTADOS.json')
        for path in sorted(source.rglob('*')):
            if not path.is_file():continue
            if path.is_symlink():raise ValueError('No reparse/symlink source allowed')
            relative=path.relative_to(source)
            receipt={'source':str(path),'relative_path':relative.as_posix(),'bytes':path.stat().st_size,'sha256':sha(path)}
            source_before[str(path)]=receipt['sha256']
            excluded=path.name.endswith('.deetsnap.gz') or path.name.startswith('RECALCULO') or '__pycache__' in path.parts or path.suffix=='.pyc'
            if excluded:
                receipt['reason']='Complete native checkpoint remains local; raw observations do not replace it' if path.name.endswith('.deetsnap.gz') else 'Earlier N0 calculation output is regenerated by the included current stdlib tool; no unique physical event is removed'
                omitted.append(receipt);continue
            destination=args.out/'EVIDENCIA'/case/relative
            destination.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(path,destination)
            selected.append({**receipt,'file':destination.relative_to(args.out).as_posix()})
    for name in('recalcular_cribados_sensores_n0.py','recalcular_aplicacion_contextual_n0.py'):
        target=args.out/'RECALCULO'/name;target.parent.mkdir(exist_ok=True);shutil.copyfile(args.lab/name,target)
    for name in('HALLAZGO_SENSOR_REUTILIZABLE_R02.md','HALLAZGO_APLICACION_CONTEXTUAL_R03.md'):
        target=args.out/'INFORMES'/name;target.parent.mkdir(exist_ok=True);shutil.copyfile(args.lab/name,target)
    code_target=args.out/'CODIGO_CIERRE'/Path(__file__).name
    code_target.parent.mkdir(exist_ok=True);shutil.copyfile(__file__,code_target)
    jobs=[];calculation_receipts=[]
    for case,script in cases:
        output=args.out/'REFERENCIAS'/(case+'.json');output.parent.mkdir(exist_ok=True)
        command=[sys.executable,'-I','-B',str(args.out/'RECALCULO'/script),
            '--evidence',str(args.out/'EVIDENCIA'/case),'--out',str(output)]
        completed=subprocess.run(command,cwd=tempfile.gettempdir(),capture_output=True,text=True,encoding='utf8',timeout=120)
        if completed.returncode:
            emit(args.out/('FALLO_N0_'+case+'.json'),{'command':command,'returncode':completed.returncode,'stdout':completed.stdout,'stderr':completed.stderr})
            raise RuntimeError('Portable calculation failed; preserve stage and original evidence')
        reference=json.loads(output.read_bytes())
        if reference['issues']:raise ValueError('Recalculation has scientific/data discrepancies')
        calculation_receipts.append({'name':case,'returncode':completed.returncode,'stdout':completed.stdout,'stderr':completed.stderr,
            'reference_sha256':sha(output),'checks':reference['checks']})
        jobs.append({'name':case,'base':'.','script':'RECALCULO/'+script,
            'args':['--evidence','EVIDENCIA/'+case,'--out','{output}'],'reference':'REFERENCIAS/'+case+'.json'})
    emit(args.out/'PLAN_RECALCULO.json',{'jobs':jobs})
    emit(args.out/'INDICE_FUENTES_Y_OMISIONES.json',{'schema':'APD03.mechanism_essential_index.v1',
        'selected_originals':selected,'omitted_originals':omitted,
        'selected_original_bytes':sum(row['bytes'] for row in selected),
        'omitted_original_bytes':sum(row['bytes'] for row in omitted),
        'scope':'Essential causal audit, not operational backup. Every unique recorded event and all actual effect files are included; complete native snapshots remain local. No motor/WHL or SQLite is included.'})
    for path,expected in source_before.items():
        if sha(path)!=expected:raise ValueError('An original changed during read-only N0 closure')
    # A new short extraction-style location must suffice. Leave it in place as
    # a reproducibility witness rather than recursively deleting anything.
    portable_root=Path(tempfile.mkdtemp(prefix='dee_apd03_mecanismo_'))
    portable=portable_root/'paquete';shutil.copytree(args.out,portable)
    proof=[]
    for job in jobs:
        generated=portable_root/(job['name']+'_RECALCULADO.json')
        command=[sys.executable,'-I','-B',str(portable/job['script']),
            '--evidence',str(portable/('EVIDENCIA/'+job['name'])),'--out',str(generated)]
        completed=subprocess.run(command,cwd=portable_root,capture_output=True,text=True,encoding='utf8',timeout=120)
        expected=portable/job['reference']
        identical=completed.returncode==0 and generated.is_file() and generated.read_bytes()==expected.read_bytes()
        proof.append({'name':job['name'],'command':command,'returncode':completed.returncode,
            'stdout':completed.stdout,'stderr':completed.stderr,'byte_identical':identical,
            'expected_sha256':sha(expected),'actual_sha256':sha(generated) if generated.is_file() else None})
        if not identical:
            emit(args.out/'PRUEBA_PORTABLE_FALLIDA.json',{'location':str(portable_root),'jobs':proof})
            raise ValueError('Exact byte portability failed; preserve output')
    emit(args.out/'PRUEBA_PORTABLE.json',{'schema':'APD03.mechanism_portable_stdlib.v1','native_ticks':0,
        'location':str(portable_root),'cases':proof,'all_byte_identical':all(row['byte_identical'] for row in proof),
        'calculations':calculation_receipts,'scope':'Archived evidence recalculation in another folder, not native reproduction, learning or another computer.'})
    files=[]
    for path in sorted(args.out.rglob('*')):
        if path.is_file():files.append({'file':path.relative_to(args.out).as_posix(),'bytes':path.stat().st_size,'sha256':sha(path)})
    emit(args.out/'MANIFIESTO.json',{'schema':'APD03.closed_mechanism_stage.v1','status':'CLOSED_RECALCULATED_PORTABLY_N0',
        'files':files,'files_count':len(files),'files_bytes':sum(row['bytes'] for row in files),
        'self_reference_excluded':'MANIFIESTO.json','portable_jobs':3,'new_native_ticks_in_closure':0})
    print(json.dumps({'stage':str(args.out),'files':len(files)+1,'bytes_without_self':sum(row['bytes'] for row in files),
        'portable_jobs':len(proof),'all_byte_identical':True,'manifest_sha256':sha(args.out/'MANIFIESTO.json')}))
    return 0


if __name__=='__main__':raise SystemExit(main())
